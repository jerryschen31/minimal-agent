func Test_Tree_FilesBeforeDirectoriesAlphabeticalWithBoxDrawing(t *testing.T) {
	pkgs := []Pkg{
		{Dir: ".", Files: []string{"z.go", "a.go"}},
		{Dir: "b", Files: []string{"d.go"}},
		{Dir: "a/sub", Files: []string{"c.go"}},
		{Dir: "a", Files: []string{"y.go", "b.go"}},
	}
	got := tree("example.com/mod", pkgs[:0:0])
	if got != "mod/\n" && got != "example.com/mod/\n" {
		t.Errorf("empty tree = %q", got)
	}
	got = tree("mod", pkgs)
	want := `mod/
├── a.go
├── z.go
├── a/
│   ├── b.go
│   ├── y.go
│   └── sub/
│       └── c.go
└── b/
    └── d.go
`
	if got != want {
		t.Errorf("got:\n%s\nwant:\n%s", got, want)
	}
}

func Test_Tree_LastEntryIsAFileWhenNoDirectoriesFollow(t *testing.T) {
	got := tree("m", []Pkg{{Dir: "d", Files: []string{"x.go"}}, {Dir: ".", Files: []string{"r.go"}}})
	want := "m/\n├── r.go\n└── d/\n    └── x.go\n"
	if got != want {
		t.Errorf("got:\n%s\nwant:\n%s", got, want)
	}
}

func Test_DirTitle(t *testing.T) {
	if got := dirTitle(Pkg{Dir: ".", Name: "m"}); got != "(root) package m" {
		t.Errorf("root: %q", got)
	}
	if got := dirTitle(Pkg{Dir: "a/b", Name: "b"}); got != "a/b (package b)" {
		t.Errorf("nested: %q", got)
	}
}

func Test_SectionLines_Layout(t *testing.T) {
	p := Pkg{Funcs: []Func{
		{Key: "A", File: "a.go", Sig: "func A()", Header: "A does it.\n\nExample:\n"},
		{Key: "B", File: "a.go", Sig: "func B(x int) error"},
		{Key: "C", File: "b.go", Sig: "func (c *T) C()"},
	}}
	got := strings.Join(sectionLines(p), "\n")
	want := strings.Join([]string{
		"// " + heading,
		"//",
		"// Generated by `go run ./cmd/codemap` from the code; do not edit by hand. Each file lists its function and",
		"// method signatures in source order.",
		"//",
		"//\ta.go",
		"//\t  func A()",
		"//\t  func B(x int) error",
		"//",
		"//\tb.go",
		"//\t  func (c *T) C()",
	}, "\n")
	if got != want {
		t.Errorf("got:\n%s\nwant:\n%s", got, want)
	}
}

func Test_SectionLines_FixtureHasOnlyFileNamesAndSignatures(t *testing.T) {
	p := pkgByDir(t, mustLoad(t, copyFixture(t)), ".")
	if funcByKey(t, p, "Documented").Header == "" {
		t.Fatal("fixture precondition: Documented must have a header")
	}
	lines := sectionLines(p)
	all := strings.Join(lines, "\n")
	for _, banned := range []string{"@", "calls:", "(no header)", "Documented has a full header", "unreviewed"} {
		if strings.Contains(all, banned) {
			t.Errorf("section contains %q:\n%s", banned, all)
		}
	}
	var entries []string
	for _, l := range lines {
		if strings.HasPrefix(l, "//\t  ") {
			entries = append(entries, strings.TrimPrefix(l, "//\t  "))
		}
	}
	if len(entries) != len(p.Funcs) {
		t.Fatalf("%d entry lines for %d funcs", len(entries), len(p.Funcs))
	}
	for i, f := range p.Funcs {
		if entries[i] != f.Sig {
			t.Errorf("entry %d = %q, want %q", i, entries[i], f.Sig)
		}
	}
}
