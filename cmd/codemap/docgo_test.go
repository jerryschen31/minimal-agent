package main

import (
	"go/format"
	"reflect"
	"strings"
	"testing"
)

const overviewDoc = "// Package x is documented by hand.\n//\n// Second paragraph of the overview.\npackage x\n"

var sectionA = []string{"// " + heading, "//", "// first body", "//\tcode A"}
var sectionB = []string{"// " + heading, "//", "// second body", "//\tcode B"}

func Test_ReplaceSection_AddsSectionWhenMissingAndKeepsOverview(t *testing.T) {
	out, err := replaceSection([]byte(overviewDoc), sectionA)
	if err != nil {
		t.Fatal(err)
	}
	s := string(out)
	for _, want := range []string{"Package x is documented by hand.", "Second paragraph of the overview.", heading, "first body", "package x"} {
		if !strings.Contains(s, want) {
			t.Errorf("output lacks %q:\n%s", want, s)
		}
	}
	if strings.Index(s, "Second paragraph") > strings.Index(s, heading) {
		t.Error("section must come after the overview")
	}
}

func Test_ReplaceSection_ReplacesExistingSectionInPlace(t *testing.T) {
	first, err := replaceSection([]byte(overviewDoc), sectionA)
	if err != nil {
		t.Fatal(err)
	}
	second, err := replaceSection(first, sectionB)
	if err != nil {
		t.Fatal(err)
	}
	s := string(second)
	if strings.Contains(s, "first body") || strings.Contains(s, "code A") {
		t.Errorf("old section survived:\n%s", s)
	}
	if !strings.Contains(s, "second body") || !strings.Contains(s, "Second paragraph of the overview.") {
		t.Errorf("new section or overview missing:\n%s", s)
	}
	if strings.Count(s, heading) != 1 {
		t.Errorf("heading appears %d times", strings.Count(s, heading))
	}
}

func Test_ReplaceSection_IsIdempotentAndGofmtStable(t *testing.T) {
	once, err := replaceSection([]byte(overviewDoc), sectionA)
	if err != nil {
		t.Fatal(err)
	}
	twice, err := replaceSection(once, sectionA)
	if err != nil {
		t.Fatal(err)
	}
	if string(once) != string(twice) {
		t.Errorf("second run changed the file:\n--- once\n%s\n--- twice\n%s", once, twice)
	}
	formatted, err := format.Source(once)
	if err != nil || string(formatted) != string(once) {
		t.Errorf("output is not gofmt-stable (err=%v)", err)
	}
}

func Test_ReplaceSection_KeepsDeclarationsAfterThePackageClause(t *testing.T) {
	src := overviewDoc + "\nimport \"fmt\"\n\nvar _ = fmt.Sprint\n"
	out, err := replaceSection([]byte(src), sectionA)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(out), "var _ = fmt.Sprint") {
		t.Errorf("code after the package clause was lost:\n%s", out)
	}
}

func Test_ReplaceSection_ErrorsWhenThereIsNoPackageComment(t *testing.T) {
	if _, err := replaceSection([]byte("package x\n"), sectionA); err == nil {
		t.Fatal("want an error for a file without a package comment")
	}
}

func Test_ReplaceSection_ErrorsOnBlockComment(t *testing.T) {
	if _, err := replaceSection([]byte("/* Package x. */\npackage x\n"), sectionA); err == nil {
		t.Fatal("want an error for a /* */ package comment")
	}
}

func Test_ReplaceSection_ErrorsOnUnparsableSource(t *testing.T) {
	if _, err := replaceSection([]byte("this is not go"), sectionA); err == nil {
		t.Fatal("want a parse error")
	}
}

func Test_ReplaceSection_TreatsAnUnrelatedCommentGroupAsNotThePackageComment(t *testing.T) {
	// A blank line between the comment and `package` makes it a floating comment, not a package comment.
	if _, err := replaceSection([]byte("// floating\n\npackage x\n"), sectionA); err == nil {
		t.Fatal("want an error: the floating comment is not a package comment")
	}
}

func Test_ExtractSection_RoundTripsWhatReplaceSectionWrote(t *testing.T) {
	out, err := replaceSection([]byte(overviewDoc), sectionA)
	if err != nil {
		t.Fatal(err)
	}
	lines, ok := extractSection(out)
	if !ok {
		t.Fatal("section not found")
	}
	joined := strings.Join(lines, "\n")
	if !strings.Contains(joined, "first body") || !strings.Contains(joined, "\tcode A") {
		t.Errorf("lines = %q", lines)
	}
	if strings.Contains(joined, "Second paragraph") || strings.Contains(joined, heading) {
		t.Errorf("extract must start after the heading and exclude the overview: %q", lines)
	}
}

func Test_ExtractSection_ReportsNotFound(t *testing.T) {
	for name, src := range map[string]string{
		"no section":      overviewDoc,
		"no comment":      "package x\n",
		"unparsable file": "garbage",
	} {
		if lines, ok := extractSection([]byte(src)); ok || lines != nil {
			t.Errorf("%s: got %v, %v", name, lines, ok)
		}
	}
}

func Test_CodeBlock(t *testing.T) {
	tests := []struct {
		name string
		in   []string
		want []string
	}{
		{"strips one tab and the prose before the block", []string{"Generated by x.", "", "\tfile.go", "\t  func A()  @1"}, []string{"file.go", "  func A()  @1"}},
		{"drops trailing blank lines", []string{"\ta", "", "  "}, []string{"a"}},
		{"keeps blank lines inside the block", []string{"\ta", "", "\tb"}, []string{"a", "", "b"}},
		{"no tab lines gives nil", []string{"just prose", ""}, nil},
		{"empty input gives nil", nil, nil},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			if got := codeBlock(tc.in); !reflect.DeepEqual(got, tc.want) {
				t.Errorf("got %q, want %q", got, tc.want)
			}
		})
	}
}
