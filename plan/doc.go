// Package plan reads and writes plan files: the formal tasks the planner LLM and Go make from an objective file, and
// the input autonomous mode runs.
//
// A plan file belongs to the machine: you write the objective file (package objective), the planner proposes tasks,
// Go checks them and writes the plan. You may still tweak a plan by hand, so Cleanup reads it leniently and reports
// each fix. When the objective changes, the plan is stale (IsStale) and is redone, keeping task IDs; each task's
// DefinitionHash lets the run state tell which tasks changed. See PLAN-plan-apply.md.
//
// Reading and writing: Cleanup is the one reader. It fixes small mistakes and reports each fix; CheckComplete then
// says whether the plan is ready to run. Markdown is the one writer, and Cleanup reads its output back unchanged with
// zero fixes (FuzzCleanup checks this). The package writes no files.
//
// Shape:
//
//	plan file (bytes)
//	   │
//	   ▼
//	Cleanup
//	   1. check and split the input (mdscan)
//	   2. read the front matter          → Format, ObjectivePath, ObjectiveHash, Version
//	   3. split the file into sections   (one per heading; heading mistakes fixed here)
//	   4. fill in each section:
//	        # Plan: <title>               → Title, Summary
//	        ## Assumptions                → Assumptions
//	        ## Tasks                      → []Task (ID, title, field lines, body)
//	        any other heading             → Other
//	   5. give each task without an ID the next free number
//	   │
//	   ▼
//	(Plan, []Fix, error)
//
//	Plan ─► Markdown() = frontMatter() + body()
//	Plan ─► CheckComplete(maxTasks) error
//	Plan ─► IsStale(objective hash)
//	Task ─► DefinitionHash()             (every field and the body, except reason)
//
// The standard layout (what Markdown writes):
//
//	---
//	format: minagent-plan/v1
//	objective: objective.md
//	objective_hash: sha256:<hex>
//	plan_version: 4
//	---
//
//	# Plan: <title>
//	<summary, optional>
//
//	## Assumptions          (optional)
//	## <any other name>     (kept as written, in file order)
//
//	## Tasks
//	<notes, optional>
//
//	### t1: <title>
//	depends: t3, t4         (each field line optional, in this order)
//	reason: <why this plan version added or changed it>
//	effects: external
//	gate: <why it must ask before running>
//	needs: <capabilities, free text>
//	done when: <how to tell it's done>
//
//	<body>
//
